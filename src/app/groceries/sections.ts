const SECTION_BY_INGREDIENT = new Map<string, Section>(
  Object.entries(INGREDIENTS_BY_SECTION).flatMap(([section, names]) =>
    names.map((name) => [name, section as Section] as const),
  ),
);

export function sectionOf(name: string): Section {
  if (AT_HOME.includes(name)) return 'Probably at home';
  return SECTION_BY_INGREDIENT.get(name) ?? 'Other';
}
